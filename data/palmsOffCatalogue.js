/** Ordered absolute image URLs for a product's gallery. */
export const palmsOffImages = (product) =>
  (product.imagePaths || []).map(palmsOffImageUrl);

/** Alt text for a gallery image — descriptive rather than "image 3". */
export const palmsOffImageAlt = (product, path) => {
  const view = String(path).replace(/^.*_([a-z0-9-]+)\.png$/i, '$1').replace(/-/g, ' ');
  const colour = product.heroColour ? ` in ${product.heroColour}` : '';
  return `${product.title}${colour} — ${view}`;
};

/** Spec rows for the product page. Only facts derived from the catalogue —
 *  nothing inferred about materials or dimensions. */
export const palmsOffSpecs = (product) => [
  { label: 'Brand', value: 'Palms Off Gaming' },
  { label: 'SKU', value: product.skus.length > 1 ? `${product.sku} (${product.skus.length} variants)` : product.sku },
  ...(product.colours.length > 0
    ? [{ label: 'Colours available', value: product.colours.join(', ') }]
    : []),
];

const BY_SLUG = Object.fromEntries(PALMS_OFF_PRODUCTS.map((p) => [p.slug, p]));

export const resolvePalmsOffProduct = (slug) =>
  (slug ? BY_SLUG[String(slug).toLowerCase()] : null) || null;

export const palmsOffProductsInCategory = (categorySlug) =>
  PALMS_OFF_PRODUCTS.filter((p) => p.categorySlug === categorySlug);

