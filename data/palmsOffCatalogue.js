/** Absolute public URL for a storage path. Segment-wise encoding: the bucket
 *  name and most folder names contain spaces, and encodeURIComponent on the
 *  whole path would swallow the "/" separators. */
export const palmsOffImageUrl = (storagePath) => {
  if (!storagePath) return null;
  const encoded = `${PALMS_OFF_BUCKET}/${storagePath}`.split('/').map(encodeURIComponent).join('/');
  return `${SUPABASE_PUBLIC_BASE}/${encoded}`;
};

