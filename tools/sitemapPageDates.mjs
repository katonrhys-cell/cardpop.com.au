// Works out data/sitemapPageDates.js: for each entry in
// data/sitemapPageSources.js, a hash of its source files and the day they last
// changed. Shared by `npm run sitemap:dates` (scripts/update-sitemap-dates.mjs)
// and tests/backend/sitemapPageDates.test.js, which fails when a hash is stale.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Files a page reads its words and figures from without listing them: its
// direct data/config imports, and the policy constants the info pages quote.
const AUTO_IMPORT = /from\s+['"]@\/((?:data|config)\/[^'"]+|utils\/(?:buyerProtectionPolicy|shopReturnPolicy|featuredPackages|businessIdentity)\.js)['"]/g;

export function expandSources(files, root = ROOT) {
  const out = new Set(files);
  for (const file of files) {
    if (!/\.jsx?$/.test(file) || !existsSync(join(root, file))) continue;
    const text = readFileSync(join(root, file), 'utf8');
    for (const match of text.matchAll(AUTO_IMPORT)) {
      if (existsSync(join(root, match[1]))) out.add(match[1]);
    }
  }
  return [...out].sort();
}

export function hashSources(files, root = ROOT) {
  const hash = createHash('sha256');
  for (const file of expandSources(files, root)) {
    hash.update(`${file}\n`);
    // Line endings normalised so a Windows checkout hashes the same.
    hash.update(readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n'));
    hash.update('\n');
  }
  return hash.digest('hex').slice(0, 16);
}

const git = (args, root) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

// The day the files last changed: today when any has uncommitted edits (or git
// can't say), else the newest commit touching them.
export function lastChanged(files, root = ROOT, today = new Date().toISOString().slice(0, 10)) {
  try {
    const all = expandSources(files, root);
    if (git(['status', '--porcelain', '--', ...all], root)) return today;
    if (git(['rev-parse', '--is-shallow-repository'], root) === 'true') return today;
    return git(['log', '-1', '--format=%cs', '--', ...all], root) || today;
  } catch {
    return today;
  }
}

// The next dates object: an entry whose hash still matches keeps its date.
export function computeDates(sources, previous = {}, root = ROOT) {
  const next = {};
  for (const key of Object.keys(sources).sort()) {
    const hash = hashSources(sources[key], root);
    const kept = previous[key]?.hash === hash && previous[key]?.lastmod;
    next[key] = { lastmod: kept || lastChanged(sources[key], root), hash };
  }
  return next;
}

export function renderDatesFile(dates) {
  const rows = Object.entries(dates)
    .map(([key, { lastmod, hash }]) => `  ${JSON.stringify(key)}: { lastmod: '${lastmod}', hash: '${hash}' },`)
    .join('\n');
  return `// GENERATED by \`npm run sitemap:dates\` — do not edit by hand.
// The day each static sitemap page's source files last changed
// (data/sitemapPageSources.js). Regenerate after changing a listed page.
export const STATIC_PAGE_DATES = {
${rows}
};
`;
}
