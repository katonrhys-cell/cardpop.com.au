-- Minimal stand-in for categories / manufacturers / sets, seeded with the
-- live NBA → Upper Deck rows as of 2026-10-18 (name, slug, series) so the
-- relabel / rename / insert steps run against real data. Used by
-- tests/db/run-nba-upper-deck-sets-migration.sh only.
create extension if not exists "uuid-ossp";
create table public.categories (id uuid primary key, name text not null, slug text not null, parent_id uuid);
create table public.manufacturers (id uuid primary key, name text not null, slug text not null, franchise_id uuid, sort_order int default 0, is_active boolean default true);
create table public.sets (
  id uuid primary key default uuid_generate_v4(),
  category_id uuid not null references public.categories(id),
  name text not null,
  slug text not null unique,
  series text,
  publisher text,
  release_date date,
  total_cards integer,
  image_url text,
  api_source text,
  api_set_id text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  manufacturer_id uuid references public.manufacturers(id)
);
